// Writes the site settings reference of the docs.typo3.org manual from the set's definitions and labels.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { format, resolveConfig } from 'prettier';
import { wrapRst } from './wrap-rst.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const set = join(root, 'typo3/packages/kumano_kodo/Configuration/Sets/Theme');
const out = join(root, 'typo3/packages/kumano_kodo/Documentation/Configuration/SiteSettings.rst');

const { categories, settings } = yaml.load(await readFile(join(set, 'settings.definitions.yaml'), 'utf8'));
const xlf = await readFile(join(set, 'labels.xlf'), 'utf8');
const labels = Object.fromEntries(
  [...xlf.matchAll(/<trans-unit id="([^"]+)">\s*<source>([\s\S]*?)<\/source>/g)].map(([, id, text]) => [id, text]),
);
const unescape = (s = '') =>
  s
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&amp;/g, '&');

const underline = (title, char) => `${title}\n${char.repeat([...title].length)}`;
const value = (v) => (v === '' || v === undefined ? '(empty)' : `\`${v}\``);
const block = (key, def) =>
  [
    `.. confval:: ${key}`,
    `    :name: ${key.replace(/\./g, '-').toLowerCase()}`,
    `    :type: ${def.type}`,
    `    :Default: ${value(def.default)}`,
    '',
    `    ${unescape(labels[`settings.${key}`] ?? key)}.${labels[`settings.description.${key}`] ? ` ${unescape(labels[`settings.description.${key}`])}` : ''}`,
    ...(def.enum ? ['', `    One of ${def.enum.map((e) => `\`${e}\``).join(', ')}.`] : []),
    '',
  ].join('\n');

const sections = Object.keys(categories)
  .filter((c) => c !== 'kumanoKodo')
  .map((c) => {
    const own = Object.entries(settings).filter(([, d]) => d.category === c);
    if (!own.length) return '';
    return `${underline(unescape(labels[`categories.${c}`] ?? c), '=')}\n\n${own.map(([k, d]) => block(k, d)).join('\n')}`;
  })
  .filter(Boolean);

const file = `..  Generated by scripts/build-docs.mjs from the site set. Do not edit.

..  _site-settings:

${underline('Site settings', '#')}

Sites › Setup › Edit settings of the site. Empty fields and colours left at their default keep the theme's value.

..  important::

    After saving, flush the frontend caches (the lightning icon in the toolbar). The settings editor clears neither the page nor the TypoScript cache, so pages keep the old values until then.

${sections.join('\n')}`;
await writeFile(out, wrapRst(file.replace(/\n{3,}/g, '\n\n')));
console.log(`Docs: ${Object.keys(settings).length} settings → ${out}`);

// The component reference: comment, arguments and slots read from each component template.
const componentsDir = join(root, 'typo3/packages/kumano_kodo/Resources/Private/Components');
const attr = (tag, name) => tag.match(new RegExp(`\\b${name}="([^"]*)"`))?.[1];
const components = [];
for (const name of (await readdir(componentsDir)).sort()) {
  const source = await readFile(join(componentsDir, name, `${name}.fluid.html`), 'utf8');
  components.push({
    name: name[0].toLowerCase() + name.slice(1),
    // One line, whatever the comment's breaks: an indented line would make RST a definition list.
    description:
      source
        .match(/<f:comment>([\s\S]*?)<\/f:comment>/)?.[1]
        .replace(/\s+/g, ' ')
        .trim() ?? '',
    arguments: [...source.matchAll(/<f:argument\b[^>]*\/>/g)].map(([tag]) => ({
      name: attr(tag, 'name'),
      type: attr(tag, 'type'),
      required: attr(tag, 'optional') !== '{true}',
      default: attr(tag, 'default'),
      description: unescape(attr(tag, 'description')),
    })),
    // Tag and inline notation: <f:slot name="x"/> and {f:slot(name: 'x')}.
    slots: [
      ...new Set(
        [...source.matchAll(/<f:slot(?:\s+name="([^"]+)")?\s*\/>|\{f:slot\((?:name:\s*'([^']+)')?\)\}/g)].map(
          ([, tag, inline]) => tag ?? inline ?? 'default',
        ),
      ),
    ],
  });
}
// Formatted as the lint expects it, so a build leaves the file unchanged when the components are.
const jsonPath = join(root, 'docs/fluid-components.json');
await writeFile(
  jsonPath,
  await format(JSON.stringify(components, null, '\t'), { ...(await resolveConfig(jsonPath, { editorconfig: true })), filepath: jsonPath }),
);

const rst = (s = '') => s.replaceAll('*', '\\*');
const code = (s) => '``' + s + '``';
const reference = components
  .map((c) => {
    const args = c.arguments.map((a) => {
      const type = [a.type, a.required ? 'required' : '', a.default ? `default ${code(a.default)}` : ''].filter(Boolean).join(', ');
      return `    *   - ${code(a.name)}\n        - ${type}\n        - ${rst(a.description)}`;
    });
    return [
      underline(`kk:${c.name}`, '='),
      '',
      rst(c.description),
      '',
      ...(args.length
        ? ['..  list-table::', '    :header-rows: 1', '', '    *   - Argument', '        - Type', '        - Meaning', ...args, '']
        : []),
      ...(c.slots.length ? [`Slots: ${c.slots.map(code).join(', ')}.`, ''] : []),
    ].join('\n');
  })
  .join('\n');
await writeFile(
  join(root, 'typo3/packages/kumano_kodo/Documentation/Components/Reference.rst'),
  wrapRst(
    `..  Generated by scripts/build-docs.mjs from the components. Do not edit.\n\n..  _component-reference:\n\n${underline('Component reference', '#')}\n\n${reference}`,
  ),
);
console.log(`Docs: ${components.length} components → Documentation/Components/Reference.rst, docs/fluid-components.json`);

// What the theme does, one line per group, from the list the Storybook start page shows in full.
const features = JSON.parse(await readFile(join(root, 'docs/features.json'), 'utf8'));
await writeFile(
  join(root, 'typo3/packages/kumano_kodo/Documentation/Features.rst.txt'),
  wrapRst(
    `..  Generated by scripts/build-docs.mjs from docs/features.json. Do not edit.\n\n` +
      features.groups.map((g) => `${g.title}\n    ${g.summary}\n`).join('\n'),
  ),
);
console.log(`Docs: ${features.groups.length} feature groups → Documentation/Features.rst.txt`);
